/**
 * A dotAI capability a provider section can configure independently.
 * Mirrors the backend `Capability` enum (com.dotcms.ai.client.langchain4j.Capability).
 */
export enum DotAiCapability {
    CHAT = 'CHAT',
    EMBEDDINGS = 'EMBEDDINGS',
    IMAGE = 'IMAGE'
}

/**
 * Primitive type of a {@link DotAiProviderField}, used to pick the right input control.
 * Mirrors the backend `ProviderFieldType` enum.
 */
export enum DotAiProviderFieldType {
    STRING = 'STRING',
    NUMBER = 'NUMBER',
    SECRET = 'SECRET'
}

/**
 * Describes a single configurable provider property for one provider/capability combination.
 * Mirrors the backend `ProviderField` record.
 */
export interface DotAiProviderField {
    name: string;
    type: DotAiProviderFieldType;
    required: boolean;
    hint: string;
    /**
     * When non-empty, the name of a sibling field whose presence satisfies this field's
     * requirement (e.g. Azure's `model` is required unless `deploymentName` is set, and vice
     * versa). Only meaningful when `required` is `false`.
     */
    requiredUnless?: string;
}

/**
 * Aggregated capability/field metadata for one dotAI provider, as returned by
 * `GET /v1/ai/providers`. Mirrors the backend `ProviderMetadata` record.
 */
export interface DotAiProviderMetadata {
    provider: string;
    supportedCapabilities: DotAiCapability[];
    fields: Partial<Record<DotAiCapability, DotAiProviderField[]>>;
}

/**
 * Result of testing a provider configuration's connection for one capability, as returned by
 * `POST /v1/ai/providers/test/{capability}`.
 */
export interface DotAiTestConnectionResult {
    success: boolean;
    message: string;
}

/* -------------------------------------------------------------------------------------------
 * dotAI admin portlet types
 *
 * The admin's own dotAI contract, deliberately separate from the published SDK types in
 * `@dotcms/types` (`libs/sdk/types/src/lib/ai/`). Those describe the SDK's `GET /ai/search`
 * query-param call style; the portlet uses `POST` with a `CompletionsForm` body, so the
 * request side is not shared at all. Coupling an internal admin screen to a versioned
 * external contract would mean an SDK change breaks the portlet and vice versa.
 *
 * New unions here are `as const` objects. The `enum`s above are an older convention — not
 * the pattern to follow.
 * ---------------------------------------------------------------------------------------- */

/** The three operators the backend actually accepts. Anything else silently becomes cosine. */
export const DOT_AI_VECTOR_OPERATOR = {
    DISTANCE: 'distance',
    COSINE: 'cosine',
    /** NOT `product` — the legacy portlet sent that, so "Inner Product" never worked. */
    INNER_PRODUCT: 'innerProduct'
} as const;

export type DotAiVectorOperator =
    (typeof DOT_AI_VECTOR_OPERATOR)[keyof typeof DOT_AI_VECTOR_OPERATOR];

/** Derived client-side: `dot_embeddings` has no status column. */
export const DOT_AI_INDEX_STATUS = {
    READY: 'READY',
    BUILDING: 'BUILDING'
} as const;

export type DotAiIndexStatus = (typeof DOT_AI_INDEX_STATUS)[keyof typeof DOT_AI_INDEX_STATUS];

