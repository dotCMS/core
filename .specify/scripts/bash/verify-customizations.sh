#!/usr/bin/env bash
#
# verify-customizations.sh — assert that the dotCMS customizations of the vendored
# Spec-Kit tree are present AND effective.
#
# Why this exists: every customization this repo layers on Spec-Kit fails by ABSENCE.
# A regeneration that quietly drops the template overrides, the ADR hook or the TDD
# gates produces no error, no failing build and no visible symptom — the flow keeps
# working and simply stops asking for the dotCMS-specific content. "It ran without
# error" is therefore not evidence of anything; this script is.
#
# The name is net-new — upstream ships nothing called this — so the checker itself
# survives `specify init --here --force` without a re-apply step, exactly like the
# customizations it checks. See .specify/CUSTOMIZATIONS.md.
#
# Usage:
#   .specify/scripts/bash/verify-customizations.sh [--verbose]
#
# Exit status: 0 when every check passes, 1 when any check fails.

set -uo pipefail

SCRIPT_DIR="$(CDPATH="" cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(CDPATH="" cd -- "$SCRIPT_DIR/../../.." && pwd)"

VERBOSE=false
for arg in "$@"; do
    case "$arg" in
        --verbose|-v) VERBOSE=true ;;
        --help|-h)
            echo "Usage: $0 [--verbose]"
            echo
            echo "Asserts the dotCMS Spec-Kit customizations are present and effective."
            echo "Exits 0 when every check passes, 1 when any check fails."
            exit 0
            ;;
        *)
            echo "ERROR: Unknown option '$arg'" >&2
            exit 2
            ;;
    esac
done

PASS_COUNT=0
FAIL_COUNT=0
FAILED_NAMES=()

# Each check function prints its own explanation on failure and returns non-zero.
# `check` runs one and records the outcome. The requirement id travels with the
# description so a failure says which requirement it belongs to without a lookup.
check() {
    local name="$1" requirement="$2" description="$3"
    shift 3
    local output status
    output="$("$@" 2>&1)"
    status=$?
    if [ $status -eq 0 ]; then
        PASS_COUNT=$((PASS_COUNT + 1))
        printf 'PASS  %-34s %s (%s)\n' "$name" "$description" "$requirement"
        if [ "$VERBOSE" = true ] && [ -n "$output" ]; then
            printf '%s\n' "$output" | sed 's/^/        /'
        fi
    else
        FAIL_COUNT=$((FAIL_COUNT + 1))
        FAILED_NAMES+=("$name")
        printf 'FAIL  %-34s %s (%s)\n' "$name" "$description" "$requirement"
        if [ -n "$output" ]; then
            printf '%s\n' "$output" | sed 's/^/        /'
        fi
    fi
}

# ---------------------------------------------------------------------------
# Checks
# ---------------------------------------------------------------------------

# T007 — the pin, the tree and the CLI that generated it must name one release.
# Today they name three, which is the drift SC-008 exists to remove.
check_version_agreement() {
    local pinned installed
    pinned=$(jq -r '.speckit_version // empty' "$REPO_ROOT/.specify/init-options.json" 2>/dev/null)
    if [ -z "$pinned" ]; then
        echo "no speckit_version recorded in .specify/init-options.json"
        return 1
    fi
    if ! command -v specify >/dev/null 2>&1; then
        echo "the specify CLI is not on PATH, so the recorded version cannot be corroborated"
        return 1
    fi
    installed=$(specify --version 2>/dev/null | grep -Eo '[0-9]+\.[0-9]+\.[0-9]+' | head -n1)
    if [ -z "$installed" ]; then
        echo "could not read a version from 'specify --version'"
        return 1
    fi
    if [ "$pinned" != "$installed" ]; then
        echo "the tree records $pinned but the installed CLI is $installed — a tree generated by neither"
        return 1
    fi
    # Sort-based comparison: the lowest version must be the floor for the pin to clear it.
    if [ "$(printf '%s\n1.0.9\n' "$pinned" | sort -V | head -n1)" != "1.0.9" ]; then
        echo "$pinned is older than the 1.0.9 floor this upgrade targets"
        return 1
    fi
    echo "pin, CLI and floor all agree on $pinned"
}

# T008 — v1.0.9 ships a managed .specify/.gitignore keeping machine-local state
# untracked. Its presence is how we know the regeneration reached the shared
# scaffolding and not only the skills.
check_managed_gitignore() {
    local f="$REPO_ROOT/.specify/.gitignore"
    if [ ! -f "$f" ]; then
        echo "$f does not exist — upstream ships it from v1.0.9 onward"
        return 1
    fi
    if ! grep -Eq '^[[:space:]]*feature\.json[[:space:]]*$' "$f"; then
        echo "$f exists but does not ignore feature.json, the per-checkout pointer it is meant to keep untracked"
        return 1
    fi
    echo "present and ignoring feature.json"
}

# T009 — patch #6. Upstream resolves feature paths by printing %q-quoted KEY=value
# lines that callers eval; Semgrep flags that as command injection. This is the
# regression guard: `--force` restores upstream's version, and nothing else fails.
check_no_eval_of_produced_strings() {
    local dir="$REPO_ROOT/.specify/scripts/bash"
    local offenders=""
    # An `eval` applied to a variable or command substitution — not the word in prose.
    offenders=$(grep -rnE '^[[:space:]]*eval[[:space:]]+["'"'"']?\$' "$dir" 2>/dev/null || true)
    if [ -n "$offenders" ]; then
        echo "a produced string is re-parsed as code:"
        echo "$offenders"
        return 1
    fi
    # The emission side: get_feature_paths() printing KEY=%q lines for a caller to eval.
    local emitters
    emitters=$(grep -rnE "printf[[:space:]]+'[A-Z_]+=%q" "$dir" 2>/dev/null || true)
    if [ -n "$emitters" ]; then
        echo "feature paths are emitted as %q-quoted assignments for a caller to eval:"
        echo "$emitters"
        return 1
    fi
    echo "no script under .specify/scripts/bash re-parses a produced string as code"
}

# >>> CHECKS END (new check functions are inserted above this line)

# ---------------------------------------------------------------------------
# Runner
# ---------------------------------------------------------------------------

run_all_checks() {
    :
    check version-agreement       "FR-002, SC-008"        "pin, installed CLI and 1.0.9 floor agree" check_version_agreement
    check managed-gitignore       "research.md R6"        "v1.0.9 .specify/.gitignore keeps feature.json untracked" check_managed_gitignore
    check no-eval                 "FR-004, FR-005, SC-003" "no vendored script re-parses a produced string as code" check_no_eval_of_produced_strings
    # >>> RUNNER END (new check invocations are inserted above this line)
}

echo "Verifying dotCMS Spec-Kit customizations in $REPO_ROOT"
echo

run_all_checks

echo
TOTAL=$((PASS_COUNT + FAIL_COUNT))
if [ "$TOTAL" -eq 0 ]; then
    echo "No checks registered."
    exit 0
fi

if [ "$FAIL_COUNT" -eq 0 ]; then
    echo "$PASS_COUNT/$TOTAL checks passed."
    exit 0
fi

echo "$PASS_COUNT/$TOTAL checks passed, $FAIL_COUNT failed: ${FAILED_NAMES[*]}"
exit 1
