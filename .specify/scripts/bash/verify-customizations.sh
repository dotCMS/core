#!/usr/bin/env bash
#
# verify-customizations.sh — assert that the dotCMS customizations of the vendored
# Spec-Kit tree are present AND effective.
#
# Why this exists: every customization this repo layers on Spec-Kit fails by ABSENCE.
# A regeneration that quietly drops the template overrides, the ADR hook or the TDD
# gates produces no error, no failing build and no visible symptom — the flow keeps
# working and simply stops asking for the dotCMS-specific content. "It ran without
# error" is therefore not evidence of anything; this script is.
#
# The name is net-new — upstream ships nothing called this — so the checker itself
# survives `specify init --here --force` without a re-apply step, exactly like the
# customizations it checks. See .specify/CUSTOMIZATIONS.md.
#
# Usage:
#   .specify/scripts/bash/verify-customizations.sh [--verbose]
#
# Exit status: 0 when every check passes, 1 when any check fails.

set -uo pipefail

SCRIPT_DIR="$(CDPATH="" cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(CDPATH="" cd -- "$SCRIPT_DIR/../../.." && pwd)"

VERBOSE=false
for arg in "$@"; do
    case "$arg" in
        --verbose|-v) VERBOSE=true ;;
        --help|-h)
            echo "Usage: $0 [--verbose]"
            echo
            echo "Asserts the dotCMS Spec-Kit customizations are present and effective."
            echo "Exits 0 when every check passes, 1 when any check fails."
            exit 0
            ;;
        *)
            echo "ERROR: Unknown option '$arg'" >&2
            exit 2
            ;;
    esac
done

PASS_COUNT=0
FAIL_COUNT=0
FAILED_NAMES=()

# Each check function prints its own explanation on failure and returns non-zero.
# `check` runs one and records the outcome. The requirement id travels with the
# description so a failure says which requirement it belongs to without a lookup.
# Read one top-level string key out of a small JSON file. Prefers jq, falls back to
# grep/sed the way common.sh does for feature.json — every other script in this
# directory provides a jq-free path, and a verifier that cannot run without jq is a
# verifier that reports false failures on a perfectly valid installation.
json_string_value() {
    local file="$1" key="$2"
    [ -f "$file" ] || { printf ''; return 0; }
    if command -v jq >/dev/null 2>&1; then
        jq -r --arg k "$key" '.[$k] // empty' "$file" 2>/dev/null
        return 0
    fi
    { grep -E "\"$key\"[[:space:]]*:" "$file" 2>/dev/null || true; } \
        | head -n 1 \
        | sed -E 's/^[^:]*:[[:space:]]*"([^"]*)".*$/\1/'
}

# Content fingerprint of every file under a directory, used to prove a read-only
# operation wrote nothing. Deliberately does not use `stat`: its format flag is -f on
# BSD and -c on GNU, and getting that wrong fails silently rather than loudly.
fingerprint_dir() {
    find "$1" -type f -exec cksum {} \; 2>/dev/null | sort
}

check() {
    local name="$1" requirement="$2" description="$3"
    shift 3
    local output status
    output="$("$@" 2>&1)"
    status=$?
    if [ $status -eq 0 ]; then
        PASS_COUNT=$((PASS_COUNT + 1))
        printf 'PASS  %-34s %s (%s)\n' "$name" "$description" "$requirement"
        if [ "$VERBOSE" = true ] && [ -n "$output" ]; then
            printf '%s\n' "$output" | sed 's/^/        /'
        fi
    else
        FAIL_COUNT=$((FAIL_COUNT + 1))
        FAILED_NAMES+=("$name")
        printf 'FAIL  %-34s %s (%s)\n' "$name" "$description" "$requirement"
        if [ -n "$output" ]; then
            printf '%s\n' "$output" | sed 's/^/        /'
        fi
    fi
}

